// Refreshes the generated parts of docs/: a copy of src/ for the playground,
// and the output of every example on the docs page. Run with `npm run docs`.
import { copyFile, mkdir, writeFile } from 'node:fs/promises'
import { plain, policy, setup, verify } from '../test/helpers.js'

const root = new URL('../', import.meta.url)
const lib = new URL('docs/lib/', root)

const SOURCES = ['index.js', 'policy.js', 'rewrite.js', 'parse.js', 'errors.js']

// [id, title, group, sql, params, uid]
const EXAMPLES = [
  ['inventory', 'My inventory', 'read', 'SELECT g.name, g.rarity, i.quantity, i.equipped\nFROM player_inventory i\nJOIN game_items g ON g.id = i.item_id\nORDER BY g.name', [], 1],
  ['inventory2', 'Same query, other player', 'read', 'SELECT g.name, g.rarity, i.quantity, i.equipped\nFROM player_inventory i\nJOIN game_items g ON g.id = i.item_id\nORDER BY g.name', [], 2],
  ['top', 'Leaderboard with avatars', 'read', 'SELECT l.rank, u.username, u.avatar_url, l.score\nFROM leaderboard l\nJOIN users u ON u.id = l.user_id\nWHERE l.season_id = ?\nORDER BY l.rank', [1], 1],
  ['star', 'SELECT * on users', 'read', 'SELECT * FROM users', [], 1],
  ['hash', 'Read password hashes', 'attack', 'SELECT username, password_hash FROM users', [], 1],
  ['sort', 'Leak emails by filtering', 'attack', "SELECT username FROM users\nWHERE email LIKE 'k%'", [], 1],
  ['sessions', 'Steal session tokens', 'attack', 'SELECT token_hash FROM auth_sessions', [], 1],
  ['or', 'Escape the row filter', 'attack', 'SELECT id, item_id, quantity\nFROM player_inventory\nWHERE id = 3 OR 1 = 1', [], 1],
  ['schema', 'Snoop the schema', 'attack', 'SELECT sql FROM sqlite_master', [], 1],
  ['stack', 'Stacked statement', 'attack', 'SELECT 1; DROP TABLE users', [], 1],
  ['blob', 'Allocate a gigabyte', 'attack', 'SELECT randomblob(1000000000)', [], 1],
  ['loot', 'Pick up an item', 'write', 'INSERT INTO player_inventory (item_id, quantity)\nVALUES (?, ?)', [2, 1], 1],
  ['gift', 'Put loot in someone else\'s bag', 'attack', 'INSERT INTO player_inventory (item_id, user_id)\nVALUES (2, 2)', [], 1],
  ['equip', 'Equip everything', 'write', 'UPDATE player_inventory SET equipped = 1', [], 1],
  ['cheat', 'Rewrite the leaderboard', 'attack', 'UPDATE leaderboard SET score = 999999\nWHERE user_id = 1', [], 1],
  ['drop', 'Throw away items', 'write', 'DELETE FROM player_inventory WHERE quantity > ?', [0], 1]
]

/** Run one example the way the docs describe it: authorize, verify, execute */
function runExample ([id, title, group, sql, params, uid]) {
  const example = { id, title, group, sql, params, uid }
  const db = setup()
  try {
    const result = policy.authorize(sql, params, { uid })
    verify(result)
    Object.assign(example, { rewritten: result.sql, boundParams: result.params, kind: result.kind })
    const stmt = db.prepare(result.sql)
    if (result.kind === 'select') {
      example.rows = plain(stmt.all(...result.params))
    } else {
      example.changes = Number(stmt.run(...result.params).changes)
      example.after = plain(db.prepare('SELECT id, user_id, item_id, quantity, equipped FROM player_inventory ORDER BY id').all())
    }
  } catch (err) {
    example.error = { code: err.code, message: err.message }
  }
  return example
}

await mkdir(lib, { recursive: true })
for (const file of SOURCES) await copyFile(new URL(`src/${file}`, root), new URL(file, lib))
await writeFile(new URL('node-sql-parser.js', lib), [
  '// Generated by `npm run docs`. The page loads node-sql-parser\'s UMD build,',
  '// which puts Parser on the global object, and the import map points',
  '// parse.js here instead of at the npm package.',
  'export default globalThis',
  ''
].join('\n'))

const examples = EXAMPLES.map(runExample)
await writeFile(new URL('docs/examples.js', root), [
  '// Generated by `npm run docs` from scripts/build-docs.js. Do not edit.',
  `window.EXAMPLES = ${JSON.stringify(examples, null, 2)}`,
  ''
].join('\n'))

console.log(`docs/lib: ${SOURCES.length} files, docs/examples.js: ${examples.length} examples`)
